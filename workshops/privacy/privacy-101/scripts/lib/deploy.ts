// Deployment of the Privacy 101 contracts, shared by scripts/deploy.ts and
// the test-suite.
import { ethers } from "hardhat";

export const CANONICAL_ERC6538_REGISTRY = "0x6538E6bf4B0eBd30A8Ea093027Ac2422ce5d6538";
export const CANONICAL_ERC5564_ANNOUNCER = "0x55649E01B5Df198D18D95b5cc5051630cfD45564";
export const SEMAPHORE_SEPOLIA = "0xC10E5102A2Cc077BE3B9740Fc0Ad7e27Ff8E0245";

export const POSEIDON_T3 = "poseidon-solidity/PoseidonT3.sol:PoseidonT3";
export const TRACING_DENOMINATION = ethers.parseEther("0.001");

export interface WorkshopAddresses {
  registry: string;
  semaphore: string;
}

export async function deployPoseidonT3() {
  const poseidon = await (await ethers.getContractFactory("PoseidonT3")).deploy();
  await poseidon.waitForDeployment();
  return poseidon;
}

export async function deployWorkshop(addresses: WorkshopAddresses, poseidonT3?: string) {
  const td = await (await ethers.getContractFactory("TDERC20_PRIVACY")).deploy("TD-Privacy-101", "TD-PRIVACY-101", 0);
  await td.waitForDeployment();

  const poseidon = poseidonT3 ?? (await deployPoseidonT3()).target;

  const naiveMixer = await (await ethers.getContractFactory("NaiveMixer")).deploy();
  const timingMixer = await (await ethers.getContractFactory("FixedMixer")).deploy(TRACING_DENOMINATION);
  const crowdMixer = await (await ethers.getContractFactory("FixedMixer")).deploy(TRACING_DENOMINATION);

  const tracing = await (await ethers.getContractFactory("EvaluatorTracing")).deploy(td.target);
  const offchain = await (await ethers.getContractFactory("EvaluatorOffchain")).deploy(td.target);
  const stealth = await (await ethers.getContractFactory("EvaluatorStealth")).deploy(td.target, addresses.registry);
  const voting = await (await ethers.getContractFactory("EvaluatorVoting")).deploy(td.target, addresses.semaphore);
  const pool = await (
    await ethers.getContractFactory("EvaluatorPool", { libraries: { [POSEIDON_T3]: poseidon } })
  ).deploy(td.target);

  const contracts = { naiveMixer, timingMixer, crowdMixer, tracing, offchain, stealth, voting, pool };
  for (const contract of Object.values(contracts)) await contract.waitForDeployment();

  for (const evaluator of [tracing, offchain, stealth, voting, pool]) {
    await (await td.setTeacher(evaluator.target, true)).wait();
  }

  return { td, poseidonT3: poseidon as string, ...contracts };
}

/// Deploys the `HonkVerifier` contract generated by Barretenberg in
/// `sourceFile` (path relative to the project root, e.g.
/// "contracts/Verifier.sol"), along with the two libraries it links against.
export async function deployHonkVerifier(sourceFile: string) {
  const libraries: Record<string, string> = {};
  for (const name of ["RelationsLib", "ZKTranscriptLib"]) {
    const library = await (await ethers.getContractFactory(`${sourceFile}:${name}`)).deploy();
    await library.waitForDeployment();
    libraries[`${sourceFile}:${name}`] = library.target as string;
  }
  const verifier = await (await ethers.getContractFactory(`${sourceFile}:HonkVerifier`, { libraries })).deploy();
  await verifier.waitForDeployment();
  return verifier;
}
